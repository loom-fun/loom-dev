"""Write docs/assets/loom-data.js from the loom-summary/1 files in summaries/.

The site reads the models from that one generated file, so no number on a page is typed by hand. Each source org's
Hugging Face avatar URL is looked up here too, so pages never call the Hub API. "gpus" lists the GPUs that at least
one model has results for (its own, or a shared section's), in gpus.json order (names and preset suffixes from gpus.json; a GPU missing there is
listed under its id), with how many models each has: the site's GPU toggle offers exactly these.

    python docs/build_data.py [--summaries summaries] [--out docs/assets/loom-data.js]
"""
import argparse
import datetime
import glob
import json
import os
import sys
import urllib.parse
import urllib.request

SCHEMA = "loom-summary/1"
HERE = os.path.dirname(os.path.abspath(__file__))
PREFIX = "window.LOOM_DATA = "


def previous_avatars(path):
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
        return json.loads(text[text.index(PREFIX) + len(PREFIX):].rstrip().rstrip(";")).get("avatars", {})
    except (OSError, ValueError):
        return {}


def avatar(name):
    """Avatar URL for a Hugging Face org or user, or None if neither lookup answers."""
    for kind in ("organizations", "users"):
        url = f"https://huggingface.co/api/{kind}/{urllib.parse.quote(name)}/avatar"
        try:
            with urllib.request.urlopen(url, timeout=10) as r:
                found = json.load(r).get("avatarUrl")
        except (OSError, ValueError):
            continue
        if found:
            return found
    return None


def gpu_ids(s):
    """The GPUs a summary has results for: its primary GPU (Strix Halo for a loom-card/2 summary) and every other
    GPU under "devices" with performance."""
    ids = [s.get("primary_device") or "strix-halo"]
    devs = s.get("devices") or {}
    has = set(ids) | {g for g, d in devs.items() if d.get("performance")}
    # a GPU that shares another's performance section (none today; the 16 GB class has its own) has that GPU's results
    shared = [g for g, d in devs.items() if g not in has and d.get("fits") and d.get("shares_section_with") in has]
    return ids + [g for g, d in devs.items() if d.get("performance")] + shared


def gpus(models, registry_path):
    with open(registry_path, encoding="utf-8") as f:
        registry = json.load(f)["gpus"]
    counts = {}
    for s in models:
        for g in gpu_ids(s):
            counts[g] = counts.get(g, 0) + 1
    known = [dict(g, models=counts[g["id"]]) for g in registry if g["id"] in counts]
    unknown = [{"id": g, "name": g, "short": g, "spec": None, "preset_suffix": None, "models": n}
               for g, n in sorted(counts.items()) if g not in {r["id"] for r in registry}]
    for g in unknown:
        print(f"warning: {g['id']} is not in gpus.json; listed under its id", file=sys.stderr)
    return known + unknown


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--summaries", default=os.path.join(HERE, "..", "summaries"))
    p.add_argument("--out", default=os.path.join(HERE, "assets", "loom-data.js"))
    p.add_argument("--gpus", default=os.path.join(HERE, "..", "gpus.json"))
    a = p.parse_args()

    models = []
    for path in sorted(glob.glob(os.path.join(a.summaries, "*.json")), key=str.lower):
        with open(path, encoding="utf-8") as f:
            s = json.load(f)
        if s.get("schema") != SCHEMA:
            sys.exit(f"{path}: schema is {s.get('schema')!r}, expected {SCHEMA!r}")
        models.append(s)

    old = previous_avatars(a.out)
    avatars = {}
    for org in sorted({m["weights"]["checkpoint"]["repo"].split("/")[0] for m in models}, key=str.lower):
        url = avatar(org) or old.get(org)
        if url:
            avatars[org] = url
        else:
            print(f"warning: no avatar for {org}", file=sys.stderr)

    data = {"generated": datetime.date.today().isoformat(), "avatars": avatars, "gpus": gpus(models, a.gpus),
            "models": models}
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by docs/build_data.py from summaries/*.json. Do not edit.\n")
        f.write(PREFIX)
        json.dump(data, f, indent=1)
        f.write(";\n")
    print(f"{len(models)} models -> {a.out}")


if __name__ == "__main__":
    main()
