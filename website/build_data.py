"""Write website/assets/loom-data.js from the loom-summary/1 files in summaries/.

The site reads the models from that one generated file, so no number on a page is typed by hand. Each source org's
Hugging Face avatar URL is looked up here too, so pages never call the Hub API.

    python website/build_data.py [--summaries summaries] [--out website/assets/loom-data.js]
"""
import argparse
import datetime
import glob
import json
import os
import sys
import urllib.parse
import urllib.request

SCHEMA = "loom-summary/1"
HERE = os.path.dirname(os.path.abspath(__file__))
PREFIX = "window.LOOM_DATA = "


def previous_avatars(path):
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
        return json.loads(text[text.index(PREFIX) + len(PREFIX):].rstrip().rstrip(";")).get("avatars", {})
    except (OSError, ValueError):
        return {}


def avatar(name):
    """Avatar URL for a Hugging Face org or user, or None if neither lookup answers."""
    for kind in ("organizations", "users"):
        url = f"https://huggingface.co/api/{kind}/{urllib.parse.quote(name)}/avatar"
        try:
            with urllib.request.urlopen(url, timeout=10) as r:
                found = json.load(r).get("avatarUrl")
        except (OSError, ValueError):
            continue
        if found:
            return found
    return None


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--summaries", default=os.path.join(HERE, "..", "summaries"))
    p.add_argument("--out", default=os.path.join(HERE, "assets", "loom-data.js"))
    a = p.parse_args()

    models = []
    for path in sorted(glob.glob(os.path.join(a.summaries, "*.json")), key=str.lower):
        with open(path, encoding="utf-8") as f:
            s = json.load(f)
        if s.get("schema") != SCHEMA:
            sys.exit(f"{path}: schema is {s.get('schema')!r}, expected {SCHEMA!r}")
        models.append(s)

    old = previous_avatars(a.out)
    avatars = {}
    for org in sorted({m["weights"]["checkpoint"]["repo"].split("/")[0] for m in models}, key=str.lower):
        url = avatar(org) or old.get(org)
        if url:
            avatars[org] = url
        else:
            print(f"warning: no avatar for {org}", file=sys.stderr)

    data = {"generated": datetime.date.today().isoformat(), "avatars": avatars, "models": models}
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by website/build_data.py from summaries/*.json. Do not edit.\n")
        f.write(PREFIX)
        json.dump(data, f, indent=1)
        f.write(";\n")
    print(f"{len(models)} models -> {a.out}")


if __name__ == "__main__":
    main()
